export function getDistrictCoords(districtName = '', stateName = 'Maharashtra', villageName = '') {
  if (!districtName && !stateName && !villageName) {
    return { lat: 20.0059, lng: 73.7900 }; // Default Nashik
  }

  const cleanVillage = String(villageName || '').trim().toLowerCase();
  const cleanDist = String(districtName || '').trim().toLowerCase();
  const cleanState = String(stateName || '').trim().toLowerCase();

  // 1. Village direct or partial match (e.g. Ajnol -> Bilaspur, HP)
  if (cleanVillage) {
    if (cleanVillage.includes('ajnol') || cleanVillage === 'ajnol') {
      return { lat: 31.3303, lng: 76.7566 };
    }
    if (DISTRICT_COORDINATES[cleanVillage]) {
      return DISTRICT_COORDINATES[cleanVillage];
    }
    for (const [key, coords] of Object.entries(DISTRICT_COORDINATES)) {
      if (cleanVillage.includes(key) || key.includes(cleanVillage)) {
        return coords;
      }
    }
  }

  // 2. State-specific overrides (e.g. Bilaspur in HP vs Chhattisgarh)
  if (cleanDist.includes('bilaspur') || cleanVillage.includes('bilaspur')) {
    if (cleanState.includes('himachal') || cleanState.includes('hp')) {
      return { lat: 31.3303, lng: 76.7566 };
    }
    if (cleanState.includes('chhattisgarh')) {
      return { lat: 22.0800, lng: 82.1554 };
    }
    return { lat: 31.3303, lng: 76.7566 };
  }

  if (cleanDist.includes('ajnol')) {
    return { lat: 31.3303, lng: 76.7566 };
  }

  // 3. Direct match on district
  if (cleanDist && DISTRICT_COORDINATES[cleanDist]) {
    return DISTRICT_COORDINATES[cleanDist];
  }

  // 4. Partial match (e.g. "kolhapur city" -> "kolhapur", "ajnol bilaspur" -> "bilaspur")
  for (const [key, coords] of Object.entries(DISTRICT_COORDINATES)) {
    if (cleanDist.includes(key) || key.includes(cleanDist)) {
      return coords;
    }
  }

  // 5. Fallback to state centroid
  if (cleanState && STATE_CENTROIDS[cleanState]) {
    return STATE_CENTROIDS[cleanState];
  }
  for (const [key, coords] of Object.entries(STATE_CENTROIDS)) {
    if (cleanState.includes(key) || key.includes(cleanState)) {
      return coords;
    }
  }

  return { lat: 20.0059, lng: 73.7900 };
}
